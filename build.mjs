// Builds index.html from index.json, merging in every { "$ref": "./file.json" }.
// Usage: node build.mjs
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));

async function load(file) {
  const path = resolvePath(root, file);
  return resolveRefs(JSON.parse(await readFile(path, "utf8")), dirname(path));
}

async function resolveRefs(value, base) {
  if (Array.isArray(value)) return Promise.all(value.map((item) => resolveRefs(item, base)));
  if (value && typeof value === "object") {
    if (typeof value.$ref === "string") return load(resolvePath(base, value.$ref));
    const entries = await Promise.all(
      Object.entries(value).map(async ([key, item]) => [key, await resolveRefs(item, base)]),
    );
    return Object.fromEntries(entries);
  }
  return value;
}

const escape = (text) =>
  String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// Pretty-printed JSON with URL strings turned into links (quotes stay outside the link).
function renderJson(data) {
  return escape(JSON.stringify(data, null, 2)).replace(
    /&quot;((?:https?:|mailto:)(?:(?!&quot;)[^\s\\])+)&quot;/g,
    (_, url) => {
      const target = url.startsWith("mailto:") ? "" : ' target="_blank" rel="noopener"';
      return `&quot;<a href="${url}"${target}>${url}</a>&quot;`;
    },
  );
}

const data = await load("index.json");
const title = escape(data.title);
const description = escape(data.about?.description ?? "");
const url = escape(data.url);
const image = escape(new URL("/og.png", data.url).href);
const author = escape(data.about?.name ?? "");
const twitter = escape("@" + ((data.about?.twitter ?? "").split("/").filter(Boolean).pop() ?? ""));

const html = `<!doctype html>
<!-- Generated by build.mjs from index.json. Do not edit by hand. -->
<html lang="en">

<head>
  <meta charset="utf-8" />

  <title>${title}</title>

  <meta property="og:url" content="${url}" />
  <meta property="og:type" content="website" />
  <meta property="og:title" content="${title}" />
  <meta property="og:description" content="${description}" />
  <meta property="og:image" content="${image}" />
  <meta property="og:image:type" content="image/png" />
  <meta property="og:image:width" content="1200" />
  <meta property="og:image:height" content="630" />

  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:site" content="${twitter}" />
  <meta name="twitter:creator" content="${twitter}" />
  <meta name="twitter:title" content="${title}" />
  <meta name="twitter:description" content="${description}" />
  <meta name="twitter:image" content="${image}" />

  <meta name="description" content="${description}" />
  <meta name="author" content="${author}" />

  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <link href="./styles.css" rel="stylesheet" />

  <link rel="apple-touch-icon" sizes="180x180" href="./apple-touch-icon.png" />
  <link rel="icon" type="image/png" sizes="32x32" href="./favicon-32x32.png" />
  <link rel="icon" type="image/png" sizes="16x16" href="./favicon-16x16.png" />
  <link rel="manifest" href="./site.webmanifest" />
  <link rel="mask-icon" href="./safari-pinned-tab.svg" color="#99c794" />
  <meta name="theme-color" content="#1b2b34" />
</head>

<body>
  <pre>${renderJson(data)}</pre>
</body>
</html>
`;

await writeFile(resolvePath(root, "index.html"), html);
console.log("Built index.html");
